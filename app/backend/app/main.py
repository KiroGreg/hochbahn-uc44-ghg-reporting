"""FastAPI entrypoint for the UC44 THG-reporting prototype.

Wires the four flow stages (upload → plausibility → prediction →
dashboard) and exposes them under `/api/...`. The OpenAPI document
served at `/openapi.json` is the source of truth for the Angular
client generated by openapi-generator-cli.

Auth: every `/api/*` router is gated by a shared bearer token in
`UC44_AUTH_TOKEN`. `/api/health` and `/api/auth/status` stay open so
nginx healthchecks and the login screen can probe without a token.
"""
from __future__ import annotations

import logging
import os
from contextlib import asynccontextmanager

from fastapi import Depends, FastAPI
from fastapi.middleware.cors import CORSMiddleware

from .api import (
    auth,
    dashboard,
    enrichment,
    plausibility,
    prediction,
    runs,
    upload,
    warengruppen,
)
from .core.auth import require_token
from .core.db import DATABASE_URL, init_db

logger = logging.getLogger("uc44")

# Which environment are we in? `local` (default) or `vm`, set via the layered
# env files (.env.defaults → .env). Purely informational: surfaced at
# /api/health and logged on startup so it's obvious which config is live.
UC44_ENV = os.getenv("UC44_ENV", "local")


def _db_kind() -> str:
    return DATABASE_URL.split(":", 1)[0]  # 'postgresql+psycopg' or 'sqlite'


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Create tables if missing (prototype-grade; swap for Alembic later).
    logger.info("Starting UC44 backend env=%s db=%s", UC44_ENV, _db_kind())
    init_db()
    yield


app = FastAPI(
    title="UC44 — THG Reporting API",
    version="0.1.0",
    description=(
        "Backend for the Hamburger Hochbahn THG-reporting prototype. "
        "Drives the four-step flow shown in the sketch: upload, "
        "plausibility check (model 1), regrouping (model 2), dashboard."
    ),
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:4200", "http://127.0.0.1:4200"],
    allow_methods=["*"],
    allow_headers=["*"],
    allow_credentials=False,
)

# `/api/auth/status` and `/api/health` are intentionally outside the
# protected scope. Everything else takes the bearer-token dependency.
_protected = [Depends(require_token)]

app.include_router(auth.router)
app.include_router(upload.router, dependencies=_protected)
app.include_router(plausibility.router, dependencies=_protected)
app.include_router(prediction.router, dependencies=_protected)
app.include_router(dashboard.router, dependencies=_protected)
app.include_router(runs.router, dependencies=_protected)
app.include_router(warengruppen.router, dependencies=_protected)
app.include_router(enrichment.router, dependencies=_protected)


@app.get("/api/health", tags=["health"], summary="Liveness probe.")
def health() -> dict:
    return {"status": "ok", "env": UC44_ENV, "db": _db_kind()}
